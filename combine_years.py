import pandas as pd
import numpy as np

def load_yearly_b4sc_data(year: int) -> pd.DataFrame:
    """
    Placeholder for loading the output of '2. create b4sc dataset.sas' for a given year.
    This would typically load dlab2.b4sc_cov_&year._junyr_full
    For standalone running, this function loads the CSV generated by create_b4sc_dataset.py
    """
    print(f"Loading enriched B4SC data for year {year}...")
    try:
        # Adjust column names to match typical Python output from previous script if needed
        # For now, assume columns match SAS output closely for direct use.
        df = pd.read_csv(f"PYTHON_b4sc_cov_{year}_junyr_full.csv", low_memory=False)
        # Ensure 'year' column is present, if not, add it from the filename.
        if 'year' not in df.columns: # The SAS output per year already has a 'year' column
            df['year'] = year
        return df
    except FileNotFoundError:
        print(f"Warning: PYTHON_b4sc_cov_{year}_junyr_full.csv not found. Returning empty DataFrame.")
        # Return an empty DataFrame with expected columns to avoid errors downstream if one file is missing
        # This schema should ideally include all columns used in the combination logic.
        # For brevity, only a few key ones are listed here.
        return pd.DataFrame({
            'year': [], 'snz_uid': [], 'hh_tenure_13': [], 'hh_tenure_18': [],
            # Add other expected _13 and _18 columns
        })


def combine_yearly_datasets(yearly_dataframes: list) -> pd.DataFrame:
    """
    Combines yearly B4SC datasets, recreates/combines census variables,
    and derives new summary variables.
    Corresponds to '3. combine years.sas'.
    """
    if not yearly_dataframes:
        print("No yearly dataframes provided. Returning empty DataFrame.")
        return pd.DataFrame()

    print("Concatenating yearly datasets...")
    # data b4sc_raw; set dlab2.b4sc_cov_2011_junyr_full ...;
    b4sc_raw_df = pd.concat(yearly_dataframes, ignore_index=True)
    print(f"Raw combined data shape: {b4sc_raw_df.shape}")

    # *Dropping old census vars as we need to recreate them below;
    cols_to_drop = [
        # SAS macro had 'parent1_lang' but R script seems to expect combined 'parent1_lang' later
        # 'parent1_lang', # This will be recreated
        'mother_no_english', # This will be recreated
        'hh_tenure', # This will be recreated
        'hh_benefit_inc', # This will be recreated based on _13 only
        # 'parent1_highest_qual', # This will be recreated
        'mother_highest_qual', # This will be recreated
        'hh_size', # This will be recreated
        # 'hh_sizhh_size', # Typo in SAS comment, likely meant just hh_size
        'n_mv_access_18', # This is a source for combined n_mv_access, SAS drops it here.
                          # Python will use it then it can be dropped if not needed.
        # SAS: los_days los_days_grp inpatient_visit_grp - these are not census vars but dropped here.
        # Python: These are not explicitly recreated in this script's logic based on combine_years.sas
        # They might be used as-is from script 2 or handled in R. For now, follow SAS drop.
        'los_days', 'los_days_grp', 'inpatient_visit_grp'
    ]
    # Drop only if they exist to avoid errors
    existing_cols_to_drop = [col for col in cols_to_drop if col in b4sc_raw_df.columns]
    b4sc_df = b4sc_raw_df.drop(columns=existing_cols_to_drop)
    print(f"Dropped specified columns. Shape: {b4sc_df.shape}")

    # --- Combine Census Variables ---
    # General logic:
    # For year <= 2015: use _13 if available, else use _18.
    # For year >= 2016: use _18 if available, else use _13.

    # Ensure 'year' column is numeric for comparisons
    b4sc_df['year'] = pd.to_numeric(b4sc_df['year'], errors='coerce')

    # Loop through census variables to combine
    census_vars_to_combine = {
        'hh_tenure': ('hh_tenure_13', 'hh_tenure_18'),
        'parent1_highest_qual': ('parent1_highest_qual_13', 'parent1_highest_qual_18'), # From SAS: parent1_highest_qual_code
        'parent1_lang': ('parent1_lang_13', 'parent1_lang_18'), # From SAS: parent1_official_language_code
        'hh_size': ('hh_size_13', 'hh_size_18'), # Numeric after conversion
        'n_mv_access': ('n_mv_access_13', 'n_mv_access_18'),
        'cen_ind_birth_country_code': ('cen_ind_birth_country_code_13', 'cen_ind_birth_country_code_18')
        # Note: SAS script also had specific handling for parent1_birth_country_code for mother_nz_born later
    }

    # Before combining, handle specific cleaning/conversion as in SAS
    # Example: parent1_highest_qual_13 in('97' '99') then parent1_highest_qual_13=''; (missing codes)
    if 'parent1_highest_qual_13' in b4sc_df.columns:
        b4sc_df['parent1_highest_qual_13'] = b4sc_df['parent1_highest_qual_13'].replace(['97', '99', 97, 99], pd.NA)
    if 'parent1_highest_qual_18' in b4sc_df.columns:
        b4sc_df['parent1_highest_qual_18'] = b4sc_df['parent1_highest_qual_18'].replace(['97', '99', 97, 99], pd.NA)

    # parent1_lang: convert to numeric, 97+ becomes NA
    if 'parent1_lang_13' in b4sc_df.columns:
        b4sc_df['parent1_lang_13_num'] = pd.to_numeric(b4sc_df['parent1_lang_13'], errors='coerce')
        b4sc_df.loc[b4sc_df['parent1_lang_13_num'] >= 97, 'parent1_lang_13_num'] = np.nan
    else: b4sc_df['parent1_lang_13_num'] = np.nan

    if 'parent1_lang_18' in b4sc_df.columns:
        b4sc_df['parent1_lang_18_num'] = pd.to_numeric(b4sc_df['parent1_lang_18'], errors='coerce')
        b4sc_df.loc[b4sc_df['parent1_lang_18_num'] >= 97, 'parent1_lang_18_num'] = np.nan
    else: b4sc_df['parent1_lang_18_num'] = np.nan
    # Update map for parent1_lang to use numeric versions
    census_vars_to_combine['parent1_lang'] = ('parent1_lang_13_num', 'parent1_lang_18_num')


    # hh_size: convert to numeric, cap at 20
    if 'hh_size_13' in b4sc_df.columns:
        b4sc_df['hh_size_13_num'] = pd.to_numeric(b4sc_df['hh_size_13'], errors='coerce')
        b4sc_df.loc[b4sc_df['hh_size_13_num'] > 20, 'hh_size_13_num'] = np.nan
    else: b4sc_df['hh_size_13_num'] = np.nan

    if 'hh_size_18' in b4sc_df.columns: # From SAS, hh_size_18 is cen_dwl_nbr_occupants_code
        b4sc_df['hh_size_18_num'] = pd.to_numeric(b4sc_df['hh_size_18'], errors='coerce')
        b4sc_df.loc[b4sc_df['hh_size_18_num'] > 20, 'hh_size_18_num'] = np.nan
    else: b4sc_df['hh_size_18_num'] = np.nan
    census_vars_to_combine['hh_size'] = ('hh_size_13_num', 'hh_size_18_num')

    # cen_ind_birth_country_code: '9999' becomes NA
    if 'cen_ind_birth_country_code_13' in b4sc_df.columns:
        b4sc_df['cen_ind_birth_country_code_13'] = b4sc_df['cen_ind_birth_country_code_13'].replace(['9999', 9999], pd.NA)
    if 'cen_ind_birth_country_code_18' in b4sc_df.columns:
        b4sc_df['cen_ind_birth_country_code_18'] = b4sc_df['cen_ind_birth_country_code_18'].replace(['9999', 9999], pd.NA)


    for target_col, (col_13, col_18) in census_vars_to_combine.items():
        # Ensure source columns exist (due to placeholders in previous script)
        col_13_exists = col_13 in b4sc_df.columns
        col_18_exists = col_18 in b4sc_df.columns

        if not col_13_exists and not col_18_exists:
            b4sc_df[target_col] = pd.NA
            continue

        val_13 = b4sc_df[col_13] if col_13_exists else pd.Series([pd.NA] * len(b4sc_df))
        val_18 = b4sc_df[col_18] if col_18_exists else pd.Series([pd.NA] * len(b4sc_df))

        b4sc_df[target_col] = np.where(
            b4sc_df['year'] <= 2015,
            np.where(val_13.notna() & (val_13 != ''), val_13, val_18), # Prioritize _13 if notna and not empty string
            np.where(val_18.notna() & (val_18 != ''), val_18, val_13)  # Prioritize _18 if notna and not empty string
        )
    print("Census variables combined.")

    # --- Derive New Variables ---
    # gp_visit_grp
    conditions_gp = [
        b4sc_df['gp_visits'] < 4, b4sc_df['gp_visits'] < 8,
        b4sc_df['gp_visits'] < 12, b4sc_df['gp_visits'] >= 12
    ]
    choices_gp = [1, 2, 3, 4]
    b4sc_df['gp_visit_grp'] = np.select(conditions_gp, choices_gp, default=pd.NA)
    b4sc_df.loc[b4sc_df['gp_visits'].isna(), 'gp_visit_grp'] = pd.NA


    # sex2 (numeric version of sex)
    # Assuming 'sex' column from script 1 is character '1'/'2' or numeric 1/2
    # If it's 'M'/'F' from script 1, this needs adjustment based on actual data from script 1.
    # The SAS script `1. create denominator pop.sas` renames `snz_sex_gender_code` to `sex`.
    # `snz_sex_gender_code` is typically numeric.
    b4sc_df['sex'] = pd.to_numeric(b4sc_df['sex'], errors='coerce') # SAS: sex2=sex*1;

    # hh_benefit_inc (uses _13 version only: inc_s7_13, inc_s8_13, etc.)
    inc_cols_13_exist = all(c in b4sc_df.columns for c in ['inc_s7_13', 'inc_s8_13', 'inc_s9_13', 'inc_s10_13'])
    if inc_cols_13_exist:
        cond_benefit_13 = (b4sc_df['inc_s7_13'] == '07') | (b4sc_df['inc_s8_13'] == '08') | \
                          (b4sc_df['inc_s9_13'] == '09') | (b4sc_df['inc_s10_13'] == '10')
        b4sc_df['hh_benefit_inc'] = np.select(
            [cond_benefit_13, b4sc_df['inc_s7_13'].notna() & (b4sc_df['inc_s7_13'] != '')], [1, 0],
            default=pd.NA # if inc_s7_13 is missing or empty
        )
    else:
        b4sc_df['hh_benefit_inc'] = pd.NA


    # hh_rent (based on combined hh_tenure)
    rent_codes_no = ['1', '10', '11', '12', '3', '30', '31', '32'] # Assuming character codes
    rent_codes_yes = ['2', '20', '21', '22']
    b4sc_df['hh_rent'] = np.select(
        [b4sc_df['hh_tenure'].astype(str).isin(rent_codes_no), b4sc_df['hh_tenure'].astype(str).isin(rent_codes_yes)],
        [0, 1], default=pd.NA
    )

    # mother_highest_qual (based on combined parent1_highest_qual)
    qual_conditions = [
        b4sc_df['parent1_highest_qual'].astype(str) == '00',
        b4sc_df['parent1_highest_qual'].astype(str).isin(['01', '02', '03', '04']),
        b4sc_df['parent1_highest_qual'].astype(str).isin(['05', '06', '07', '08', '09', '10']),
        b4sc_df['parent1_highest_qual'].astype(str).isin(['11', '12', '13', '14'])
    ]
    qual_choices = [0, 1, 2, 3]
    b4sc_df['mother_highest_qual'] = np.select(qual_conditions, qual_choices, default=pd.NA)

    # mother_no_english (based on combined parent1_lang)
    # combined parent1_lang is numeric after cleaning in this script
    no_english_lang_codes = [11, 13, 22, 23, 26, 33, 51]
    b4sc_df['mother_no_english'] = np.select(
        [b4sc_df['parent1_lang'].isin(no_english_lang_codes), b4sc_df['parent1_lang'].notna()],
        [1, 0], default=pd.NA # if parent1_lang is NA
    )

    # hh_size_grp (based on combined hh_size)
    # combined hh_size is numeric after cleaning
    hh_size_conditions = [
        b4sc_df['hh_size'] < 5,
        b4sc_df['hh_size'] < 8, # SAS: <8 implies 5,6,7 for group 2
        b4sc_df['hh_size'] >= 7 # SAS: ge 7. This overlaps with <8. SAS logic: if hh_size<5 then 1; else if hh_size<8 then 2; else if hh_size ge 8 then 3;
                               # Corrected logic:
    ]
    hh_size_choices = [1, 2, 3]
    # Corrected conditions for hh_size_grp based on typical SAS if/else if
    b4sc_df['hh_size_grp'] = np.select(
        [b4sc_df['hh_size'] < 5,
         (b4sc_df['hh_size'] >= 5) & (b4sc_df['hh_size'] < 8), # 5, 6, 7
         b4sc_df['hh_size'] >= 8], # SAS had >=7 for group 3 in comments, but >=8 in code for b4sc_cov script. Sticking to SAS code from script 2.
        hh_size_choices, default=pd.NA
    )


    # n_mv_access (recategorize combined version: if >=3 then 2)
    b4sc_df['n_mv_access_num'] = pd.to_numeric(b4sc_df['n_mv_access'], errors='coerce')
    b4sc_df.loc[b4sc_df['n_mv_access_num'] >= 3, 'n_mv_access_num'] = 2
    b4sc_df['n_mv_access'] = b4sc_df['n_mv_access_num'] # Store it back or keep as num

    # child_nz_born
    # if cen_ind_birth_country_code='1201' then child_nz_born=1;
    # else if parent1_snz_uid ne . then child_nz_born=1; (proxy for birth record found)
    # else child_nz_born=0;
    b4sc_df['child_nz_born'] = 0 # Default to 0 (not born in NZ)
    b4sc_df.loc[b4sc_df['cen_ind_birth_country_code'].astype(str) == '1201', 'child_nz_born'] = 1
    # If parent1_snz_uid has a value (meaning child likely found in birth records), also consider NZ born.
    # This logic might need refinement based on actual meaning of parent1_snz_uid presence.
    if 'parent1_snz_uid' in b4sc_df.columns: # Check if column exists
        b4sc_df.loc[b4sc_df['parent1_snz_uid'].notna() & (b4sc_df['child_nz_born'] == 0), 'child_nz_born'] = 1
    # If cen_ind_birth_country_code is NA and parent1_snz_uid is NA, it will remain 0.

    # mother_nz_born
    # IF year le 2015 THEN mother_birth_place = parent1_birth_country_code_13;
    # ELSE IF year ge 2016 THEN mother_birth_place = parent1_birth_country_code_18; (from script 2)
    # IF mother_birth_place = "1201" THEN mother_nz_born = 1; ELSE mother_nz_born = 0;
    # Note: parent1_birth_country_code_13/18 are not in census_vars_to_combine,
    # so they should be directly available from merges in script 2.
    b4sc_df['mother_birth_place_temp'] = pd.NA
    if 'parent1_birth_country_code_13' in b4sc_df.columns:
      b4sc_df.loc[b4sc_df['year'] <= 2015, 'mother_birth_place_temp'] = b4sc_df['parent1_birth_country_code_13']
    if 'parent1_birth_country_code_18' in b4sc_df.columns: # Check if col exists from script 2
      b4sc_df.loc[b4sc_df['year'] >= 2016, 'mother_birth_place_temp'] = b4sc_df['parent1_birth_country_code_18']

    b4sc_df['mother_nz_born'] = 0 # Default to 0
    b4sc_df.loc[b4sc_df['mother_birth_place_temp'].astype(str) == '1201', 'mother_nz_born'] = 1
    b4sc_df.loc[b4sc_df['mother_birth_place_temp'].isna(), 'mother_nz_born'] = 0 # If birthplace is unknown, SAS sets to 0.
    b4sc_df.drop(columns=['mother_birth_place_temp'], inplace=True, errors='ignore')


    print("Derived variables created.")

    # Creating grp_ta_ward_name
    # This requires 'ta_ward_name' which should be ta_ward_name_final from script 2
    # Assuming 'ta_ward_name_final' from script 2 is now 'ta_ward_name' in b4sc_df
    if 'ta_ward_name_final' in b4sc_df.columns:
        b4sc_df.rename(columns={'ta_ward_name_final':'ta_ward_name'}, inplace=True, errors='ignore')

    conditions_ta_group = {
        "Waitomo & Otorohanga": ["Waitomo District", "Otorohanga District"],
        "Waimate & Mackenzie": ["Waimate District", "Mackenzie District"],
        "Hurunui & Kaikoura": ["Kaikoura District", "Hurunui District"],
        "Westland & Grey": ["Westland District", "Grey District"],
        "Carterton & Sth Wairarapa": ["Carterton District", "South Wairarapa District"],
        "Kawerau & Whakatane": ["Kawerau District", "Whakatane District"],
        "Queenstown & Central Otago": ["Queenstown-Lakes District", "Central Otago District"],
        "Gore & Southland": ["Gore District", "Southland District"]
    }
    b4sc_df['grp_ta_ward_name'] = b4sc_df['ta_ward_name'] # Default to original
    for group_name, constituents in conditions_ta_group.items():
        if 'ta_ward_name' in b4sc_df.columns: # Check for placeholder
            b4sc_df.loc[b4sc_df['ta_ward_name'].isin(constituents), 'grp_ta_ward_name'] = group_name
    print("Grouped TA/Ward names created.")

    # Create non-completion vars
    for check_type in ['vht', 'nurse', 'sdqt']:
        complete_col = f'{check_type}_complete'
        incomplete_col = f'{check_type}_incomplete'
        if complete_col in b4sc_df.columns: # Check for placeholder
            b4sc_df[incomplete_col] = np.select(
                [b4sc_df[complete_col] == 0, b4sc_df[complete_col] == 1],
                [1, 0], default=pd.NA
            )
        else: # Placeholder
            b4sc_df[incomplete_col] = pd.NA


    # Compress single quotes
    cols_to_compress = ['dhb2015_name', 'ta_ward_name', 'grp_ta_ward_name']
    for col in cols_to_compress:
        if col in b4sc_df.columns: # Check for placeholder
            b4sc_df[col] = b4sc_df[col].astype(str).str.replace("'", "", regex=False)
            b4sc_df.loc[b4sc_df[col]=='nan', col] = '' # remove 'nan' if original was NA

    print("Final variable processing complete.")

    # Drop temporary columns used for combining census vars if any remain (e.g. _num versions)
    cols_to_drop_temp = [col for col in b4sc_df.columns if '_num' in col or '_13' in col or '_18' in col] # simplistic, be more specific if needed
    # More specific drops based on what was created:
    specific_temp_cols = ['parent1_lang_13_num', 'parent1_lang_18_num', 'hh_size_13_num', 'hh_size_18_num', 'n_mv_access_num']
    # Also drop original _13 and _18 source columns if they are not needed further
    for _, (col13, col18) in census_vars_to_combine.items():
        if col13 not in specific_temp_cols: specific_temp_cols.append(col13)
        if col18 not in specific_temp_cols: specific_temp_cols.append(col18)

    existing_cols_to_drop_final = [col for col in specific_temp_cols if col in b4sc_df.columns]
    if existing_cols_to_drop_final:
      b4sc_df.drop(columns=existing_cols_to_drop_final, inplace=True, errors='ignore')


    return b4sc_df


# --- Script Execution ---
if __name__ == "__main__":
    print("--- Main execution for combining years started ---")

    yearly_dfs = []
    for year_val_loop in [2011, 2012, 2013, 2014, 2015, 2016, 2017, 2018]:
        print(f"\n--- Loading data for year {year_val_loop} ---")
        yearly_df = load_yearly_b4sc_data(year=year_val_loop)
        if not yearly_df.empty:
            yearly_dfs.append(yearly_df)
        else:
            print(f"Skipping year {year_val_loop} as no data was loaded.")

    if yearly_dfs:
        print("\n--- Combining all loaded yearly datasets ---")
        final_combined_df = combine_yearly_datasets(yearly_dfs)

        print(f"\nFinal combined dataset shape: {final_combined_df.shape}")

        output_filename = "PYTHON_b4sc_allyr_FINAL.csv"
        final_combined_df.to_csv(output_filename, index=False)
        print(f"Saved final combined dataset to: {output_filename}")
    else:
        print("No data loaded for any year. Exiting.")

    print("--- Main execution for combining years finished ---")

